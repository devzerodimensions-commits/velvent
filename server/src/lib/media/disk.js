import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { query } from '../../db.js';

/**
 * Images kept on the server's own disk.
 *
 * For a host with storage that survives a restart. The database then holds
 * only the filename, so backups stay small and a dump restores in seconds
 * rather than minutes.
 *
 * MEDIA_DIR says where. It is created on first use, and the path is resolved
 * once at startup so nothing that arrives in a request can reach outside it.
 */

const ROOT = path.resolve(process.env.MEDIA_DIR || './uploads');

const EXTENSIONS = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'image/avif': '.avif',
};

/**
 * A stored name is random, never the one that was uploaded.
 *
 * An uploaded filename is attacker-controlled: "../../.env" and friends are
 * the oldest trick there is, and even once that is handled, two people
 * uploading photo.jpg must not overwrite each other. The original name is
 * kept in the database for display; only this one touches the filesystem.
 */
const storedName = (mime) => crypto.randomBytes(16).toString('hex') + (EXTENSIONS[mime] || '.bin');

/**
 * Resolves a key inside ROOT, refusing anything that climbs out.
 *
 * Keys are generated by this module, so this should never fire — but a path
 * built from a database value is exactly the kind of thing that is safe until
 * someone edits a row by hand.
 */
function resolveKey(key) {
  const full = path.resolve(ROOT, key);
  if (full !== ROOT && !full.startsWith(ROOT + path.sep)) {
    throw new Error('Refusing to read outside the media directory.');
  }
  return full;
}

export const disk = {
  id: 'disk',
  label: 'On the server disk',

  async put(file) {
    await fs.mkdir(ROOT, { recursive: true });
    const key = storedName(file.mimetype);
    await fs.writeFile(resolveKey(key), file.buffer);
    return { key, bytes: file.buffer.length };
  },

  async get(key) {
    const { rows } = await query('SELECT mime, storage_key FROM media WHERE id = $1', [key]);
    const row = rows[0];
    if (!row?.storage_key) return null;

    try {
      return { mime: row.mime, bytes: await fs.readFile(resolveKey(row.storage_key)) };
    } catch {
      // A row whose file has gone is a 404, not a crash.
      return null;
    }
  },

  async remove(storageKey) {
    if (!storageKey) return;

    /* Resolved outside the try on purpose. A key that climbs out of the media
       directory must be refused loudly; wrapping this in the same catch that
       forgives a missing file would turn a refusal into a shrug. */
    const full = resolveKey(storageKey);

    try {
      await fs.unlink(full);
    } catch (err) {
      // Already gone is the outcome we wanted. Anything else is not.
      if (err.code !== 'ENOENT') throw err;
    }
  },
};
